"""Reproducible training and evaluation for every ACSAF model.

Usage::

    python -m ml.experiments.run_all            # train, evaluate, publish
    python -m ml.experiments.run_all --quick    # smaller run, for CI
    python -m ml.experiments.run_all --no-save  # evaluate without publishing

Everything is derived from :data:`ml.config.GLOBAL_SEED`. Two runs of this
module on the same machine produce byte-identical metrics; the reported figures
in ``docs/ML_METHODOLOGY.md`` are regenerated by running it, not transcribed by
hand.

Results are written to ``ml/results/results.json`` and printed as a table.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time
import warnings
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np

from ml.config import ARTIFACT_DIR, GLOBAL_SEED, RESULTS_DIR
from ml.datasets.generators import (
    generate_bandit_logs,
    generate_risk_dataset,
    generate_security_dataset,
    generate_sequence_dataset,
)
from ml.features import FEATURE_NAMES, extract, to_matrix
from ml.registry import ModelCard, ModelRegistry

logging.basicConfig(
    level=logging.INFO, format="%(asctime)s  %(levelname)-7s %(message)s"
)
logger = logging.getLogger("experiments")

# MinCovDet warns about determinant increases on well-conditioned data; the
# fallback path in AnomalyDetector already handles genuine singularity.
warnings.filterwarnings("ignore", category=RuntimeWarning, module="sklearn.covariance")


def _feature_matrix(dataset: Any) -> np.ndarray:
    return to_matrix(
        extract(
            context,
            app_profile=dataset.app_profiles.get(context.foreground_app),
            history=history,
        )
        for context, history in zip(dataset.contexts, dataset.histories)
    )


# ----------------------------------------------------------------------
# 1. Risk classifier
# ----------------------------------------------------------------------


def run_risk_experiment(registry: ModelRegistry, *, quick: bool, save: bool) -> dict:
    from ml.risk.evaluate import evaluate_risk_model
    from ml.risk.model import RiskClassifier
    from ml.risk.safety import SafetyEnvelope

    n_train = 4000 if quick else 16000
    n_test = 1500 if quick else 6000

    logger.info("Risk: generating %s train / %s test contexts", n_train, n_test)
    train = generate_risk_dataset(n_train, label="risk-train")
    test = generate_risk_dataset(n_test, label="risk-test")

    X_train, X_test = _feature_matrix(train), _feature_matrix(test)

    logger.info("Risk: fitting and selecting by cross-validated Brier score")
    started = time.perf_counter()
    classifier = RiskClassifier().fit(X_train, train.labels)
    fit_seconds = time.perf_counter() - started

    evaluation = evaluate_risk_model(
        classifier,
        X_test,
        test.labels,
        contexts=test.contexts,
        bayes_accuracy=test.bayes_accuracy,
    )

    # The comparison that carries the argument: the rule engine's own risk
    # judgement on exactly the same held-out contexts.
    rule_predictions = np.array(
        [
            1 if SafetyEnvelope.ceiling(c)[1] in ("medium", "high") else 0
            for c in test.contexts
        ]
    )
    from ml.risk.evaluate import _cost

    rule_cost = _cost(test.labels, rule_predictions)
    rule_recall = float(
        np.mean(rule_predictions[test.labels == 1])
        if (test.labels == 1).any()
        else 0.0
    )
    rule_fpr = float(
        np.mean(rule_predictions[test.labels == 0])
        if (test.labels == 0).any()
        else 0.0
    )

    # Subgroup comparison. These two populations are where the rules are known
    # to fail, so this is where a learned model has to demonstrate value.
    subgroup_comparison: dict[str, dict[str, float]] = {}
    for name, attribute in (
        ("hidden_sensitive", "is_hidden_sensitive"),
        ("benign_critical", "is_benign_critical"),
    ):
        mask = np.array([getattr(c, attribute) for c in test.contexts])
        if not mask.any():
            continue
        positives = mask & (test.labels == 1)
        negatives = mask & (test.labels == 0)
        model_predictions = classifier.predict(X_test)
        subgroup_comparison[name] = {
            "n": int(mask.sum()),
            "model_recall": float(
                np.mean(model_predictions[positives]) if positives.any() else 0.0
            ),
            "rule_recall": float(
                np.mean(rule_predictions[positives]) if positives.any() else 0.0
            ),
            "model_false_positive_rate": float(
                np.mean(model_predictions[negatives]) if negatives.any() else 0.0
            ),
            "rule_false_positive_rate": float(
                np.mean(rule_predictions[negatives]) if negatives.any() else 0.0
            ),
        }

    results = evaluation.to_dict()
    results["fit_seconds"] = fit_seconds
    results["training_metadata"] = classifier.training_metadata
    results["rule_baseline"] = {
        "expected_cost_per_decision": rule_cost,
        "recall": rule_recall,
        "false_positive_rate": rule_fpr,
        "cost_reduction_by_model": (
            (rule_cost - evaluation.expected_cost_per_decision) / rule_cost
            if rule_cost
            else 0.0
        ),
    }
    results["subgroup_comparison"] = subgroup_comparison

    if save:
        registry.save(
            "risk_classifier",
            classifier,
            ModelCard(
                name="risk_classifier",
                version="",
                created_at="",
                intended_use=(
                    "Estimate the probability that a helpee's current device "
                    "context contains sensitive content, so the adaptive policy "
                    "engine can select an assistance mode. Output is a "
                    "suggestion bounded by the rule-based safety envelope."
                ),
                out_of_scope_use=(
                    "Must not be used to grant a capability the rule envelope "
                    "forbids, to make any decision without the helpee's "
                    "explicit consent, or as evidence about a person's "
                    "behaviour or trustworthiness."
                ),
                training_data=(
                    "Synthetic contexts from ml.datasets.generators with a "
                    "documented generative process. No real user data was used "
                    "or is available; see docs/ML_METHODOLOGY.md."
                ),
                n_training_samples=int(len(train.labels)),
                model_type=classifier.model_name,
                selection_criterion="cross-validated Brier score",
                metrics={
                    "roc_auc": evaluation.roc_auc,
                    "pr_auc": evaluation.pr_auc,
                    "brier_score": evaluation.brier_score,
                    "expected_calibration_error": evaluation.expected_calibration_error,
                    "recall": evaluation.recall,
                    "expected_cost_per_decision": evaluation.expected_cost_per_decision,
                },
                limitations=[
                    "Trained entirely on synthetic data. Reported metrics "
                    "describe the simulator, not real usage.",
                    "Features are supplied by the client and are therefore "
                    "attacker-influenceable; the rule envelope keys on "
                    "OS-provided signals for this reason.",
                    "Calibration is expected to drift as the app population "
                    "changes; recalibrate against production data before "
                    "relying on the probability.",
                    f"Abstains on the cost-equivalence band "
                    f"{classifier.abstention_band()}, where the rule engine "
                    f"decides instead.",
                ],
                ethical_considerations=[
                    "Errors are asymmetric by design: a false 'safe' can expose "
                    "an elderly person's financial data, so the threshold is "
                    "set from a 10:1 cost ratio rather than at 0.5.",
                    "The model never grants a capability; it can only propose "
                    "one at or below the rule ceiling.",
                    "Decisions are logged with their features so any outcome "
                    "can be explained to the person it affected.",
                ],
                hyperparameters=classifier.training_metadata,
                feature_names=list(FEATURE_NAMES),
            ),
        )

    return results


