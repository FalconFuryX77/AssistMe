# 4. Anomaly detector
# ----------------------------------------------------------------------


def run_anomaly_experiment(registry: ModelRegistry, *, quick: bool, save: bool) -> dict:
    from ml.anomaly.detector import AnomalyDetector
    from ml.anomaly.evaluate import evaluate_detector

    n_normal = 3000 if quick else 12000
    n_attack = 160 if quick else 640

    logger.info("Anomaly: generating %s normal / %s attack observations", n_normal, n_attack)
    train = generate_security_dataset(n_normal, n_attack, label="sec-train")
    test = generate_security_dataset(
        n_normal // 2, n_attack // 2, label="sec-test"
    )

    detector = AnomalyDetector().fit(train.features, train.feature_names)
    evaluation = evaluate_detector(
        detector, test.features, test.labels, test.scenario
    )

    if save:
        registry.save(
            "anomaly_detector",
            detector,
            ModelCard(
                name="anomaly_detector",
                version="",
                created_at="",
                intended_use=(
                    "Flag pairing and session behaviour that is unlike typical "
                    "legitimate use, for a second confirmation to the helpee or "
                    "for human review."
                ),
                out_of_scope_use=(
                    "Must not block a session, ban an account, or be presented "
                    "to any user as a finding of fraud. An anomaly score is a "
                    "prompt to look, not a verdict."
                ),
                training_data=(
                    f"{n_normal} synthetic normal observations plus {n_attack} "
                    "injected attacks across three scenarios, of which a "
                    "majority are blended toward normal behaviour."
                ),
                n_training_samples=n_normal + n_attack,
                model_type="IsolationForest + robust Mahalanobis, rank-averaged",
                selection_criterion="PR-AUC and precision@k at review-queue capacities",
                metrics=evaluation.to_dict(),
                limitations=[
                    "Unsupervised: it detects unusualness, not malice. An "
                    "unusual but legitimate helper will be flagged.",
                    "Attack scenarios are hand-specified; a novel pattern that "
                    "mimics normal behaviour closely will be missed.",
                    "Legitimate behaviour drifts, so the threshold needs "
                    "periodic refitting or it will alert on ordinary change.",
                ],
                ethical_considerations=[
                    "Telling someone their family member looks suspicious is "
                    "harmful when wrong, so the operating point favours "
                    "precision and the output is advisory.",
                    "Scores must never be shown as accusations, and every "
                    "alert carries its top contributing features so a human "
                    "can judge it.",
                ],
                hyperparameters={
                    "contamination": detector.contamination,
                    "alert_quantile": detector.alert_quantile,
                },
                feature_names=list(train.feature_names),
            ),
        )

    return evaluation.to_dict()


# ----------------------------------------------------------------------
# Safety invariant check
# ----------------------------------------------------------------------


def run_safety_audit(*, quick: bool) -> dict:
    """Exhaustively verify the envelope's invariants.

    Not a statistical evaluation — an enumeration. The safety property is
    absolute ("no proposal ever exceeds the ceiling"), so it is checked by
    trying every mode against every context rather than by sampling and
    reporting a rate. A single violation is a failure.
    """
    from ml.config import ACTION_INDEX
    from ml.risk.safety import SafetyEnvelope

    n = 2000 if quick else 8000
    dataset = generate_risk_dataset(n, label="safety-audit")

    violations = 0
    clamped = 0
    checks = 0
    high_risk_with_interaction = 0

    for context in dataset.contexts:
        ceiling, rule_risk, _ = SafetyEnvelope.ceiling(context)
        for proposed in (*ACTION_INDEX, "not-a-mode", ""):
            checks += 1
            decision = SafetyEnvelope.apply(context, proposed)
            if ACTION_INDEX.get(decision.action, 0) > ACTION_INDEX[ceiling]:
                violations += 1
            if decision.clamped:
                clamped += 1
            if rule_risk == "high" and decision.action in {"pointer", "drawing", "tap"}:
                high_risk_with_interaction += 1

    return {
        "checks_performed": checks,
        "ceiling_violations": violations,
        "clamped_proposals": clamped,
        "clamp_rate": clamped / checks if checks else 0.0,
        "high_risk_interaction_grants": high_risk_with_interaction,
        "passed": violations == 0 and high_risk_with_interaction == 0,
    }


# ----------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quick", action="store_true", help="smaller run, for CI")
    parser.add_argument("--no-save", action="store_true", help="do not publish artefacts")
    parser.add_argument(
        "--only",
        choices=["risk", "bandit", "sequence", "anomaly", "safety"],
        help="run a single experiment",
    )
    args = parser.parse_args(argv)

    save = not args.no_save
    registry = ModelRegistry()
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    started = time.perf_counter()
    results: dict[str, Any] = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "global_seed": GLOBAL_SEED,
        "quick_mode": args.quick,
        "artifact_dir": str(ARTIFACT_DIR),
    }

    experiments = {
        "safety": lambda: run_safety_audit(quick=args.quick),
        "risk": lambda: run_risk_experiment(registry, quick=args.quick, save=save),
        "bandit": lambda: run_bandit_experiment(registry, quick=args.quick, save=save),
        "sequence": lambda: run_sequence_experiment(registry, quick=args.quick, save=save),
        "anomaly": lambda: run_anomaly_experiment(registry, quick=args.quick, save=save),
    }

    for name, run in experiments.items():
        if args.only and args.only != name:
            continue
        logger.info("=== %s ===", name)
        results[name] = run()

    results["total_seconds"] = time.perf_counter() - started

    output = RESULTS_DIR / "results.json"
    output.write_text(json.dumps(results, indent=2, default=str), encoding="utf-8")
    logger.info("Wrote %s", output)

    _print_summary(results)
    return 0


def _print_summary(results: dict[str, Any]) -> None:
    """Print the tables that go into the methodology document."""
    print()
    print("=" * 78)
    print(f"ACSAF model evaluation — seed {results['global_seed']}")
    print("=" * 78)

    if "safety" in results:
        audit = results["safety"]
        status = "PASS" if audit["passed"] else "FAIL"
        print(f"\nSafety envelope audit: {status}")
        print(f"  checks performed         {audit['checks_performed']:,}")
        print(f"  ceiling violations       {audit['ceiling_violations']}")
        print(f"  high-risk interaction    {audit['high_risk_interaction_grants']}")

    if "risk" in results:
        r = results["risk"]
        print("\nRisk classifier")
        print(f"  selected model           {r['training_metadata']['selected_model']}")
        print(f"  ROC-AUC / PR-AUC         {r['roc_auc']:.4f} / {r['pr_auc']:.4f}"
              f"  (no-skill PR {r['pr_auc_no_skill']:.4f})")
        print(f"  Brier / ECE              {r['brier_score']:.4f} / {r['expected_calibration_error']:.4f}")
        print(f"  recall / precision       {r['recall']:.4f} / {r['precision']:.4f}")
        print(f"  expected cost            {r['expected_cost_per_decision']:.4f}"
              f"  (rules {r['rule_baseline']['expected_cost_per_decision']:.4f},"
              f" {r['rule_baseline']['cost_reduction_by_model']*100:+.1f}%)")
        print(f"  abstention rate          {r['abstention_rate']:.4f}")
        print("  subgroup recall (model vs rules):")
        for name, m in r.get("subgroup_comparison", {}).items():
            print(f"    {name:20s} {m['model_recall']:.3f} vs {m['rule_recall']:.3f}"
                  f"   (n={m['n']})")

    if "bandit" in results:
        b = results["bandit"]
        print("\nContextual bandit — cumulative regret")
        print(f"    {'policy':18s} {'regret':>10s} {'tail rate':>10s} {'optimal%':>9s} {'unsafe':>7s}")
        for name, m in sorted(b["regret"].items(), key=lambda kv: kv[1]["final_regret"]):
            print(f"    {name:18s} {m['final_regret']:10.1f} {m['terminal_regret_rate']:10.4f}"
                  f" {m['optimal_action_rate']*100:8.1f}% {m['safety_violations']:7d}")
        print("\n  Off-policy value estimates (true value in brackets)")
        print(f"    {'policy':18s} {'IPS':>8s} {'SNIPS':>8s} {'DR':>8s} {'true':>8s} {'ESS':>9s}")
        for name, m in b["off_policy_evaluation"].items():
            true_value = m.get("true_value")
            print(f"    {name:18s} {m['ips']:8.4f} {m['snips']:8.4f} {m['dr']:8.4f}"
                  f" {true_value if true_value is None else f'{true_value:8.4f}'}"
                  f" {m['effective_sample_size']:9.1f}")

    if "sequence" in results:
        print("\nNext-action recommendation")
        print(f"    {'model':18s} {'R@1':>7s} {'R@3':>7s} {'MRR':>7s} {'cold R@3':>9s}")
        for name, m in results["sequence"].items():
            print(f"    {name:18s} {m['recall_at_1']:7.4f} {m['recall_at_3']:7.4f}"
                  f" {m['mrr']:7.4f} {m['cold_start_recall_at_3']:9.4f}")

    if "anomaly" in results:
        a = results["anomaly"]
        print("\nSecurity anomaly detection")
        print(f"  ROC-AUC / PR-AUC         {a['roc_auc']:.4f} / {a['pr_auc']:.4f}"
              f"  (no-skill {a['pr_auc_no_skill']:.4f})")
        print(f"  precision / recall       {a['precision']:.4f} / {a['recall']:.4f}"
              f"  at {a['alert_rate']*100:.1f}% alert rate")
        print("  per-scenario recall:")
        for name, value in a.get("per_scenario_recall", {}).items():
            print(f"    {name:22s} {value:.3f}")

    print(f"\nTotal runtime: {results.get('total_seconds', 0):.1f}s")
    print("=" * 78)


if __name__ == "__main__":
    sys.exit(main())
