# 3. Sequence recommender
# ----------------------------------------------------------------------


def run_sequence_experiment(registry: ModelRegistry, *, quick: bool, save: bool) -> dict:
    from ml.sequence.evaluate import evaluate_recommender, split_sessions
    from ml.sequence.markov import MarkovRecommender
    from ml.sequence.neural import NeuralSequenceRecommender, PopularityRecommender

    n_sessions = 1500 if quick else 6000
    n_users = 120 if quick else 320

    logger.info("Sequence: generating %s sessions from %s users", n_sessions, n_users)
    dataset = generate_sequence_dataset(n_sessions, n_users)
    train_seq, train_users, test_seq, test_users = split_sessions(
        dataset.sequences, dataset.user_ids
    )

    evaluations: dict[str, Any] = {}

    markov = MarkovRecommender().fit(train_seq, train_users)
    evaluations["markov_backoff"] = evaluate_recommender(
        markov, train_seq, train_users, test_seq, test_users,
        model_name="markov_backoff",
    ).to_dict()

    popularity = PopularityRecommender().fit(train_seq, train_users)
    evaluations["popularity"] = evaluate_recommender(
        popularity, train_seq, train_users, test_seq, test_users,
        model_name="popularity", uses_full_history=True,
    ).to_dict()

    neural = NeuralSequenceRecommender().fit(train_seq, train_users)
    evaluations["neural_mlp"] = evaluate_recommender(
        neural, train_seq, train_users, test_seq, test_users,
        model_name="neural_mlp", uses_full_history=True,
    ).to_dict()

    # The Markov chain is published even when the neural model edges ahead:
    # it updates online, is explainable to a helper, and adds no dependency to
    # the request path. The comparison is reported so that choice is visible
    # and arguable rather than assumed.
    if save:
        registry.save(
            "sequence_recommender",
            markov,
            ModelCard(
                name="sequence_recommender",
                version="",
                created_at="",
                intended_use=(
                    "Suggest the next assistance action a helper is likely to "
                    "need, ranked, and intersected with the admissible set."
                ),
                out_of_scope_use=(
                    "Suggestions are never executed automatically and never "
                    "widen what the policy engine permits."
                ),
                training_data=(
                    f"{len(train_seq)} synthetic assistance sessions with "
                    "per-user behavioural bias."
                ),
                n_training_samples=len(train_seq),
                model_type="first-order Markov chain with Jelinek-Mercer backoff",
                selection_criterion=(
                    "Recall@3 and MRR on a chronological session split with "
                    "held-out cold-start users; simplicity preferred at equal "
                    "performance"
                ),
                metrics=evaluations["markov_backoff"],
                limitations=[
                    "First-order: conditions only on the immediately previous "
                    "action, so a longer-range dependency is invisible to it.",
                    "Suggestions reflect what helpers have done before, which "
                    "will reinforce existing habits including poor ones.",
                    "Synthetic sequences follow a hand-specified workflow; real "
                    "sessions will be messier.",
                ],
                ethical_considerations=[
                    "Suggesting remote control makes it more likely to be "
                    "requested, so suggestions are filtered through the safety "
                    "envelope before display.",
                    "Per-user models are built from that user's own history "
                    "only and are never shared between accounts.",
                ],
                hyperparameters={"smoothing": markov.smoothing},
                feature_names=list(markov.actions),
            ),
        )

    return evaluations


