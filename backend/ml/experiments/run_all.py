# 2. Contextual bandit
# ----------------------------------------------------------------------


def run_bandit_experiment(registry: ModelRegistry, *, quick: bool, save: bool) -> dict:
    from ml.bandit.evaluate import compare_policies
    from ml.bandit.ope import evaluate_policy_offline
    from ml.bandit.policies import (
        EpsilonGreedyPolicy,
        LeastPrivilegePolicy,
        LinUCBPolicy,
        MaxPrivilegePolicy,
        RandomPolicy,
        ThompsonSamplingPolicy,
    )

    n_samples = 3000 if quick else 10000
    n_rounds = 1500 if quick else 6000
    n_seeds = 3 if quick else 5
    thompson_samples = 32 if quick else 128

    logger.info("Bandit: generating %s logged decisions", n_samples)
    logs = generate_bandit_logs(n_samples)
    dimension = logs.features.shape[1]

    factories = {
        "random": lambda: RandomPolicy(),
        "least_privilege": lambda: LeastPrivilegePolicy(),
        "rule_ceiling": lambda: MaxPrivilegePolicy(),
        "epsilon_greedy": lambda: EpsilonGreedyPolicy(dimension),
        "linucb": lambda: LinUCBPolicy(dimension),
        "thompson": lambda: ThompsonSamplingPolicy(
            dimension, n_probability_samples=thompson_samples
        ),
    }

    logger.info("Bandit: online regret simulation (%s seeds)", n_seeds)
    regret = compare_policies(
        factories,
        logs.features,
        logs.admissible,
        logs.reward_table,
        n_rounds=n_rounds,
        n_seeds=n_seeds,
    )

    # Off-policy evaluation. Policies are pre-trained on the logged data so the
    # estimate describes a *trained* policy, which is what would be deployed —
    # evaluating an untrained one measures nothing useful.
    logger.info("Bandit: off-policy evaluation (IPS / SNIPS / DR)")
    ope: dict[str, dict] = {}
    for name in ("least_privilege", "rule_ceiling", "linucb", "thompson"):
        policy = factories[name]()
        if hasattr(policy, "update"):
            for i in range(len(logs.features)):
                policy.update(
                    logs.features[i], int(logs.actions[i]), float(logs.rewards[i])
                )
        result = evaluate_policy_offline(
            policy,
            logs.features,
            logs.actions,
            logs.propensities,
            logs.rewards,
            logs.admissible,
            reward_table=logs.reward_table,
        )
        ope[name] = {
            k: v
            for k, v in vars(result).items()
            if not k.startswith("_")
        }

    # Publish the best online performer.
    best_name = min(regret, key=lambda k: regret[k].final_regret)
    trained = factories[best_name]()
    if hasattr(trained, "update"):
        for i in range(len(logs.features)):
            trained.update(
                logs.features[i], int(logs.actions[i]), float(logs.rewards[i])
            )

    if save and best_name in {"linucb", "thompson", "epsilon_greedy"}:
        best = regret[best_name]
        registry.save(
            "assistance_bandit",
            trained,
            ModelCard(
                name="assistance_bandit",
                version="",
                created_at="",
                intended_use=(
                    "Select an assistance mode from the admissible set the "
                    "safety envelope permits, balancing helpfulness against "
                    "over-assistance."
                ),
                out_of_scope_use=(
                    "Must not select outside the admissible set, and must not "
                    "explore on a context the envelope marks high risk."
                ),
                training_data=(
                    f"{n_samples} synthetic logged decisions with recorded "
                    "propensities under an epsilon-greedy logging policy."
                ),
                n_training_samples=n_samples,
                model_type=best_name,
                selection_criterion="lowest cumulative regret in online simulation",
                metrics={
                    "final_regret": best.final_regret,
                    "terminal_regret_rate": best.terminal_regret_rate,
                    "optimal_action_rate": best.optimal_action_rate,
                    "safety_violations": best.safety_violations,
                    "dr_estimated_value": ope.get(best_name, {}).get("dr"),
                },
                limitations=[
                    "Reward is simulated. The real reward signal (task "
                    "resolved, control revoked, session abandoned) must be "
                    "instrumented before deployment.",
                    "Assumes reward is linear in the features; the true "
                    "relationship is probably not.",
                    "Exploration means an occasional deliberately suboptimal "
                    "mode. Set ML_BANDIT_EXPLORATION=0 to disable it.",
                ],
                ethical_considerations=[
                    "Exploration happens on real assistance sessions with "
                    "vulnerable users, so it is confined to the admissible set "
                    "and never trades safety for information.",
                    "Reward penalises over-assistance as well as "
                    "under-assistance, encoding that doing things for someone "
                    "is not automatically helping them.",
                ],
                hyperparameters={
                    "policy": best_name,
                    "n_rounds": n_rounds,
                    "n_seeds": n_seeds,
                },
                feature_names=list(FEATURE_NAMES),
            ),
        )

    return {
        "regret": {
            name: {
                "final_regret": r.final_regret,
                "final_regret_std": r.final_regret_std,
                "terminal_regret_rate": r.terminal_regret_rate,
                "mean_reward": r.mean_reward,
                "oracle_mean_reward": r.oracle_mean_reward,
                "optimal_action_rate": r.optimal_action_rate,
                "safety_violations": r.safety_violations,
                "action_distribution": r.action_distribution,
                "regret_curve_sampled": r.mean_cumulative_regret[:: max(1, n_rounds // 40)],
            }
            for name, r in regret.items()
        },
        "off_policy_evaluation": ope,
        "best_policy": best_name,
        "logged_policy_value": float(np.mean(logs.rewards)),
    }


