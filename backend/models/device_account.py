"""Device-first account model.

Maps a physical install (stable fingerprint) to an invisible user account so
the app needs no email/password login. A one-time recovery code is the root
credential for reclaiming the identity after reinstall or device loss.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import DateTime, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column

from core.database import Base


class DeviceAccount(Base):
    """A physical install bound to its (invisible) user account."""

    __tablename__ = "device_accounts"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )
    user_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True,
    )
    # Stable per-install identity generated by the client.
    fingerprint: Mapped[str] = mapped_column(String(128), unique=True, nullable=False)
    # SHA-256 of the one-time recovery code shown to the user at onboarding.
    recovery_code_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
